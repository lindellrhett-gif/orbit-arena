// Wraps the single-file build as a TypeScript module the Expo app imports: mobile/src/webApp.ts
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync(new URL('../dist-native/index.html', import.meta.url), 'utf8');
const out = `// Generated by \`npm run build:native\` from the web app. Don't edit by hand.\nexport const WEB_APP_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(new URL('../mobile/src/webApp.ts', import.meta.url), out);
console.log(`mobile/src/webApp.ts: ${(out.length / 1024).toFixed(0)} KB`);
